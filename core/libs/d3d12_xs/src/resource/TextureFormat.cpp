#include "Texture.hpp"
#include <array>

AnyBox::Graphics::TextureFormatDescription AnyBox::Graphics::TextureFormat(DXGI_FORMAT format) {
    struct Entry { DXGI_FORMAT source; VkFormat target; std::uint32_t hardware; };
    constexpr std::array<Entry, 25> formats{{
        {DXGI_FORMAT_R32G32B32A32_FLOAT, VK_FORMAT_R32G32B32A32_SFLOAT, 77},
        {DXGI_FORMAT_R32G32B32A32_UINT, VK_FORMAT_R32G32B32A32_UINT, 75},
        {DXGI_FORMAT_R32G32B32A32_SINT, VK_FORMAT_R32G32B32A32_SINT, 76},
        {DXGI_FORMAT_R16G16B16A16_FLOAT, VK_FORMAT_R16G16B16A16_SFLOAT, 71},
        {DXGI_FORMAT_R16G16B16A16_UNORM, VK_FORMAT_R16G16B16A16_UNORM, 65},
        {DXGI_FORMAT_R16G16B16A16_UINT, VK_FORMAT_R16G16B16A16_UINT, 69},
        {DXGI_FORMAT_R16G16B16A16_SNORM, VK_FORMAT_R16G16B16A16_SNORM, 66},
        {DXGI_FORMAT_R16G16B16A16_SINT, VK_FORMAT_R16G16B16A16_SINT, 70},
        {DXGI_FORMAT_R32G32_FLOAT, VK_FORMAT_R32G32_SFLOAT, 64},
        {DXGI_FORMAT_R32G32_UINT, VK_FORMAT_R32G32_UINT, 62},
        {DXGI_FORMAT_R32G32_SINT, VK_FORMAT_R32G32_SINT, 63},
        {DXGI_FORMAT_R11G11B10_FLOAT, VK_FORMAT_B10G11R11_UFLOAT_PACK32, 36},
        {DXGI_FORMAT_R8G8B8A8_UNORM, VK_FORMAT_R8G8B8A8_UNORM, 56},
        {DXGI_FORMAT_R8G8B8A8_UNORM_SRGB, VK_FORMAT_R8G8B8A8_SRGB, 130},
        {DXGI_FORMAT_R8G8B8A8_UINT, VK_FORMAT_R8G8B8A8_UINT, 60},
        {DXGI_FORMAT_R8G8B8A8_SNORM, VK_FORMAT_R8G8B8A8_SNORM, 57},
        {DXGI_FORMAT_R8G8B8A8_SINT, VK_FORMAT_R8G8B8A8_SINT, 61},
        {DXGI_FORMAT_R16G16_FLOAT, VK_FORMAT_R16G16_SFLOAT, 29},
        {DXGI_FORMAT_R16G16_UNORM, VK_FORMAT_R16G16_UNORM, 23},
        {DXGI_FORMAT_R32_FLOAT, VK_FORMAT_R32_SFLOAT, 22},
        {DXGI_FORMAT_R32_UINT, VK_FORMAT_R32_UINT, 20},
        {DXGI_FORMAT_R32_SINT, VK_FORMAT_R32_SINT, 21},
        {DXGI_FORMAT_R16_FLOAT, VK_FORMAT_R16_SFLOAT, 13},
        {DXGI_FORMAT_R16_UNORM, VK_FORMAT_R16_UNORM, 7},
        {DXGI_FORMAT_R8_UNORM, VK_FORMAT_R8_UNORM, 1}
    }};
    for (const auto& entry : formats) if (entry.source == format) return {entry.target, entry.hardware};
    throw std::runtime_error("Texture Vulkan format mapping is not implemented");
}
